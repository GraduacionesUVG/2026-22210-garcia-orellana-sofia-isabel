import { test, expect } from '../fixtures';
import { assertWorkspaceOperable } from '../browser-assertions';

test.describe('corpus catalogs via modal', () => {
  test('source edit cancellation is local then exact source update survives reload and document option readback', async ({ page, ui }, testInfo) => {
    const id = 'GAP03-source';
    ui.seed({ sources: [{ id, project_id: ui.projectId, code: 'gap03_source', label: 'GAP03 original source', position: 0, is_active: true, revision: 2, deleted_at: null }] });
    await page.goto(`/projects/${ui.projectId}/corpus`);
    await page.getByRole('button', { name: /Fuentes.*Define el origen/ }).click();
    await page.getByRole('button', { name: 'Editar fuente GAP03 original source', exact: true }).click();
    await page.getByPlaceholder('Entrevista docente').fill('GAP03 canceled source');
    await page.getByRole('button', { name: /Cancelar/ }).click();
    expect(ui.requests.filter(row => row.method === 'PATCH' && row.path.includes('/documents/sources/'))).toHaveLength(0);
    await page.getByRole('button', { name: 'Editar fuente GAP03 original source', exact: true }).click();
    await page.getByPlaceholder('Entrevista docente').fill('GAP03 edited source Ñandú');
    await page.getByRole('button', { name: /Actualizar$/ }).filter({ visible: true }).last().click();
    await expect(page.getByRole('button', { name: 'Editar fuente GAP03 edited source Ñandú', exact: true })).toBeVisible();
    expect(ui.requests.filter(row => row.method === 'PATCH' && row.path.includes('/documents/sources/')).map(row => row.path)).toEqual([`/api/projects/${ui.projectId}/documents/sources/${id}`]);
    await page.getByRole('button', { name: 'Cerrar configuración', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: /Fuentes.*Define el origen/ }).click();
    await expect(page.getByRole('button', { name: 'Editar fuente GAP03 edited source Ñandú', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Editar fuente GAP03 original source', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Cerrar configuración', exact: true }).click();
    await page.getByRole('button', { name: /Nueva transcripción/ }).last().click();
    await expect(page.getByRole('option', { name: 'GAP03 edited source Ñandú', exact: true })).toHaveCount(1);
    await expect(page.getByRole('option', { name: 'GAP03 canceled source', exact: true })).toHaveCount(0);
    await testInfo.attach('GAP03-source-requests', { body: JSON.stringify(ui.requests), contentType: 'application/json' });
  });
  test('participant and source create edit cancel and populate the document selector', async ({ page, ui }) => {
    await page.goto(`/projects/${ui.projectId}/corpus`);
    await page.getByRole('button', { name: /Participantes.*Crea alias/ }).click();
    const modal = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Participantes y fuentes' }) });
    await expect(modal.getByText('Nombre visible').locator('..')).toContainText('(opcional)');
    await expect(modal.getByPlaceholder('Ej. P01').locator('..').locator('..')).toContainText('Alias*');
    await modal.getByPlaceholder('Ej. P01').fill('PÑ01');
    await modal.getByPlaceholder('Ej. Participante 01').fill('Participante 🧪');
    await modal.getByRole('button', { name: /Crear$/, exact: false }).click();
    await expect(modal.getByRole('button', { name: 'Editar participante PÑ01' })).toBeVisible();
    await modal.getByRole('button', { name: 'Editar participante PÑ01' }).click();
    await modal.getByPlaceholder('Ej. P01').fill('Cancelado');
    await modal.getByRole('button', { name: /Cancelar/ }).click();
    expect(ui.requests.filter(request => request.method === 'PATCH' && request.path.includes('/participants/'))).toHaveLength(0);
    await modal.getByRole('button', { name: 'Editar participante PÑ01' }).click();
    await modal.getByPlaceholder('Ej. Participante 01').fill('Participante editada');
    await modal.getByRole('button', { name: /Actualizar$/, exact: false }).click();
    await expect(modal.getByText('Participante editada', { exact: true })).toBeVisible();
    await modal.getByRole('button', { name: /Fuentes$/, exact: false }).click();
    await modal.getByPlaceholder('entrevista_docente').fill('historia_oral');
    await modal.getByPlaceholder('Entrevista docente').fill('Historia oral Ñandú');
    await modal.getByRole('button', { name: /Crear$/, exact: false }).click();
    await expect(modal.getByRole('button', { name: 'Editar fuente Historia oral Ñandú' })).toBeVisible();
    await modal.getByRole('button', { name: 'Cerrar configuración' }).click();
    await assertWorkspaceOperable(page);
    await page.getByRole('button', { name: /Nueva transcripción/ }).last().click();
    await expect(page).toHaveURL(new RegExp(`/projects/${ui.projectId}/corpus/new$`));
    const participantId = ui.dataset.participants[0].id, sourceId = ui.dataset.sources[0].id;
    const selects = page.locator('select');
    await selects.filter({ has: page.getByRole('option', { name: 'Historia oral Ñandú', exact: true }) }).selectOption(sourceId);
    await selects.filter({ has: page.getByRole('option', { name: 'PÑ01 · Participante editada', exact: true }) }).selectOption(participantId);
    await page.getByPlaceholder('Ej. Entrevista P01 sobre prácticas educativas').fill('Historia con catálogos');
    await page.getByPlaceholder('Pega aquí la entrevista, nota de campo, observación o texto cualitativo...').fill('Texto cualitativo vinculado.');
    await page.getByRole('button', { name: /Guardar transcripción/ }).click();
    await expect(page).toHaveURL(new RegExp(`/projects/${ui.projectId}/corpus$`));
    const created = ui.requests.find(request => request.method === 'POST' && request.path.endsWith('/documents'))!;
    expect(created.body).toMatchObject({ source_id: sourceId, participant_id: participantId });
    await page.reload(); await expect(page.getByRole('link', { name: 'Abrir documento Historia con catálogos' })).toBeVisible();
  });

  test('stale participant revision displays conflict without false success', async ({ page, ui }) => {
    const id = 'participant-conflict';
    await ui.seed({ participants: [{ id, alias: 'P01', display_name: '', status: 'active', notes: '', attributes: {}, deleted_at: null, revision: 3 }] });
    ui.mockApi.route('PATCH', `/api/projects/${ui.projectId}/participants/${id}`, () => ({ status: 409, json: { ok: false, error: 'PARTICIPANT_REVISION_CONFLICT' } }));
    await page.goto(`/projects/${ui.projectId}/corpus`);
    await page.getByRole('button', { name: /Participantes.*Crea alias/ }).click();
    await page.getByRole('button', { name: 'Editar participante P01' }).click();
    await page.getByPlaceholder('Ej. Participante 01').fill('Cambio pendiente');
    await page.getByRole('button', { name: /Actualizar$/, exact: false }).filter({ visible: true }).last().click();
    await expect(page.getByText(/PARTICIPANT_REVISION_CONFLICT|modificado/).filter({ visible: true }).first()).toBeVisible();
    await expect(page.getByPlaceholder('Ej. Participante 01')).toHaveValue('Cambio pendiente');
    await expect(page.getByText(/actualizado correctamente/)).toHaveCount(0);
  });
});
